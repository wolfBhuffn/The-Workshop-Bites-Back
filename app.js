function navigateTo(pageId) {
  var targetSection = document.getElementById(pageId);
  if (!targetSection) return;

  var sections = document.querySelectorAll(".section");
  for (var i = 0; i < sections.length; i++) {
    sections[i].classList.remove("active");
  }

  var buttons = document.querySelectorAll(".tab-btn");
  for (var j = 0; j < buttons.length; j++) {
    if (buttons[j].getAttribute("data-target") === pageId) {
      buttons[j].classList.add("active");
    } else {
      buttons[j].classList.remove("active");
    }
  }

  targetSection.classList.add("active");
  if (window.history && window.history.replaceState) {
    window.history.replaceState(null, "", "#" + pageId);
  }
}

function setupNavigation() {
  var buttons = document.querySelectorAll("#main-nav .tab-btn");
  for (var i = 0; i < buttons.length; i++) {
    buttons[i].addEventListener("click", function () {
      navigateTo(this.getAttribute("data-target"));
    });
  }

    var initialHash = window.location.hash.replace("#", "");
  var hashTarget = initialHash ? document.getElementById(initialHash) : null;
  if (hashTarget && hashTarget.classList.contains("section")) {
    navigateTo(initialHash);
  }
}

function renderEpisodes() {
  var grid = document.getElementById("episode-grid");
  grid.innerHTML = "";

  for (var i = 0; i < seriesData.length; i++) {
    var ep = seriesData[i];

    var card = document.createElement("div");
    card.className = "card";

    var topWrap = document.createElement("div");

    var imgEl = document.createElement("img");
    imgEl.className = "card-img";
    imgEl.src = ep.image;
    imgEl.alt = ep.number + " - " + ep.title;

    var sub = document.createElement("div");
    sub.className = "subtitle";
    sub.textContent = ep.number + " • " + ep.runtime + " • " + ep.status;

    var heading = document.createElement("h3");
    heading.textContent = ep.title;

    var desc = document.createElement("p");
    desc.textContent = ep.summary;

    topWrap.appendChild(imgEl);
    topWrap.appendChild(sub);
    topWrap.appendChild(heading);
    topWrap.appendChild(desc);

    var btn = document.createElement("button");
    btn.type = "button";
    btn.className = "btn-secondary";
    btn.textContent = "Open Script & Prompts";
    btn.setAttribute("data-ep-id", ep.id);
    btn.addEventListener("click", function () {
      var chosenId = this.getAttribute("data-ep-id");
      navigateTo("studio");
      loadScript(chosenId);
    });

    card.appendChild(topWrap);
    card.appendChild(btn);
    grid.appendChild(card);
  }
}

function renderStudioControls() {
  var selector = document.getElementById("script-selector");
  selector.innerHTML = "";

  for (var i = 0; i < seriesData.length; i++) {
    var ep = seriesData[i];
    var btn = document.createElement("button");
    btn.type = "button";
    btn.className = "btn-secondary";
    btn.textContent = ep.number + ": " + ep.title;
    btn.setAttribute("data-ep-id", ep.id);
    btn.addEventListener("click", function () {
      loadScript(this.getAttribute("data-ep-id"));
    });
    selector.appendChild(btn);
  }

  loadScript("ep1");
}

function loadScript(epId) {
  var ep = null;
  for (var i = 0; i < seriesData.length; i++) {
    if (seriesData[i].id === epId) {
      ep = seriesData[i];
      break;
    }
  }
  if (!ep) return;

  var viewer = document.getElementById("script-viewer");
  viewer.innerHTML = "";

  var sub = document.createElement("div");
  sub.className = "subtitle";
  sub.textContent = ep.number + " • Target Runtime: " + ep.runtime;

  var heading = document.createElement("h3");
  heading.textContent = '"' + ep.title + '" — Beat-by-Beat Breakdown';

  var list = document.createElement("ul");
  list.className = "beat-list";

  for (var j = 0; j < ep.beats.length; j++) {
    var beat = ep.beats[j];

    var li = document.createElement("li");
    li.className = "beat-item";

    var timeDiv = document.createElement("div");
    timeDiv.className = "beat-time";
    timeDiv.textContent = beat.time;

    var actionP = document.createElement("p");
    actionP.className = "beat-text";
    actionP.innerHTML = "<strong>Visual:</strong> " + beat.action;

    var audioP = document.createElement("p");
    audioP.className = "beat-audio";
    audioP.innerHTML = "<strong>Audio/SFX:</strong> " + beat.audio;

    var copyBtn = document.createElement("button");
    copyBtn.type = "button";
    copyBtn.className = "copy-prompt-btn";
    copyBtn.textContent = "Copy AI Image Prompt";
    copyBtn.setAttribute("data-prompt", beat.prompt);
    copyBtn.addEventListener("click", function () {
      var buttonRef = this;
      var promptToCopy = buttonRef.getAttribute("data-prompt");
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(promptToCopy);
      }
      buttonRef.textContent = "Copied!";
      setTimeout(function () {
        buttonRef.textContent = "Copy AI Image Prompt";
      }, 1500);
    });

    li.appendChild(timeDiv);
    li.appendChild(actionP);
    li.appendChild(audioP);
    li.appendChild(copyBtn);
    list.appendChild(li);
  }

  viewer.appendChild(sub);
  viewer.appendChild(heading);
  viewer.appendChild(list);
}

